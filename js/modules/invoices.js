const statusTag = (s) => {
  const cls = s === "PAID" ? "green" : s === "PARTIALLY PAID" ? "orange" : "red";
  return `<span class="tag ${cls}">${s}</span>`;
};

function makePaymentModal(invoiceId, ctx, onComplete) {
  const inv = db.get("invoices", invoiceId);
  if (!inv || inv.balance <= 0) return toast("Invoice already fully paid.");

  const amtInp = input({ type: "number", value: inv.balance, style: "font-weight:bold; font-size:18px;" });
  
  const m = modal({
    title: `Receive Payment`,
    size: "sm",
    body: el("div", {}, [
      el("div", { style: "margin-bottom:12px; font-size:13px; color:var(--muted)" }, `Invoice: ${inv.invoiceNo} | Balance: ${naira(inv.balance)}`),
      field("Amount (₦)", amtInp)
    ]),
    footer: [
      btn("Submit Payment", {
        variant: "success",
        onclick: async () => {
          const amount = num(amtInp.value);
          if (amount <= 0 || amount > inv.balance) return toast("Invalid payment amount.", "error");
          try {
            await applyPayment(inv, { amount, cashier: ctx?.user?.name || "" });
            toast("Payment received successfully!", "success");
            m.close();
            if (typeof onComplete === "function") onComplete();
          } catch (err) {
            toast(err.message, "error");
          }
        }
      })
    ]
  });
}


// Asynchronous batch renderer to prevent browser crash on 500+ invoices
async function renderInvoicesBatch(invoices, onProgress) {
  const htmlChunks = [];
  const batchSize = 25;
  for (let i = 0; i < invoices.length; i += batchSize) {
    const batch = invoices.slice(i, i + batchSize);
    
    // Yield to browser UI thread to keep it responsive
    await new Promise(res => setTimeout(res, 50));
    
    for (const inv of batch) {
      const student = db.get("students", inv.studentId);
      // Append the invoice wrapped in a page-break container
      htmlChunks.push(`<div class="invoice-page">${invoiceDoc(inv, student)}</div>`);
    }
    
    if (onProgress) onProgress(Math.min(i + batchSize, invoices.length), invoices.length);
  }
  return htmlChunks.join("");
}

export function showInvoice(invoiceId, { afterClose } = {}) {
  const inv = db.get("invoices", invoiceId);
  if (!inv) return toast("Invoice not found", "error");
  const student = db.get("students", inv.studentId);
  const html = invoiceDoc(inv, student);
  const body = el("div", {});
  const preview = el("div", { class: "doc-preview" });
  preview.innerHTML = `<style>${PRINT_CSS}</style><div class="doc a4-fit">${html}</div>`;
  body.appendChild(preview);
  const m = modal({
    title: `Invoice ${inv.invoiceNo}`, size: "lg", body, onClose: afterClose,
    footer: [
      btn("Print", { icon: "🖨️", onclick: () => previewHtml(html, { title: "Invoice " + inv.invoiceNo }) }),
      btn("Download PDF", { onclick: () => downloadPdf(html, { title: "Invoice " + inv.invoiceNo, filename: `Invoice_${inv.invoiceNo}.pdf` }) }),
      btn("WhatsApp", { variant: "success", onclick: () => {
        const phone = student?.parentPhone || student?.guardianPhone || "";
        shareDocumentToWhatsApp(html, { title: "Invoice " + inv.invoiceNo, filename: `Invoice_${inv.invoiceNo}.png`, phone });
      } }),
      btn("Close", { variant: "primary", onclick: () => m.close() })
    ]
  });
}

